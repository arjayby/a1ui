function dotPath(packed: string) {
  const digit = (index: number) => DIGITS.indexOf(packed[index]);
  let path = "";
  for (let i = 0; i + 4 < packed.length; i += 5) {
    const x = (digit(i) * 64 + digit(i + 1)) / 4;
    const y = (digit(i + 2) * 64 + digit(i + 3)) / 4;
    const r = digit(i + 4) / 10;
    path += `M${x - r},${y}a${r},${r} 0 1,0 ${r * 2},0a${r},${r} 0 1,0 -${r * 2},0`;
  }
  return path;
}

const paths = Object.fromEntries(
  Object.entries(MATRIX).map(([shape, packed]) => [shape, dotPath(packed)]),
) as Record<MenuGlyphShape, string>;

export function MenuGlyph({ shape, ...props }: ComponentProps<"svg"> & { shape: MenuGlyphShape }) {
  return (
    <svg viewBox="0 0 120 120" aria-hidden="true" {...props}>
      <path d={paths[shape]} fill="currentColor" />
    </svg>
  );
}
